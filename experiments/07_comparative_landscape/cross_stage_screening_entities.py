#!/usr/bin/env python3
"""
Experiment 07 offline cross-stage screening-entity construction.

This module combines the already-frozen database and citation identity layers.

It does NOT:
- modify either frozen discovery corpus;
- modify the frozen identity implementation;
- perform network requests;
- resolve identity conflicts;
- perform scientific screening;
- choose software/method identities;
- choose canonical publications; or
- write production result files.

Automatic cross-stage publication linkage is conservative:

1. exact DOI when PMID evidence does not point to another database entity;
2. for DOI-less citation entities only, exact PMID when it maps to exactly
   one database publication entity.

Different DOI identities are never bridged through PMID.
"""

from __future__ import annotations

import argparse
import hashlib
import json

from collections import Counter, defaultdict
from pathlib import Path
from typing import Iterable

import screening_entity_identity as identity


HERE = Path(__file__).resolve().parent

IDENTITY_IMPLEMENTATION = (
    HERE / "screening_entity_identity.py"
)

FROZEN_IDENTITY_IMPLEMENTATION_SHA256 = (
    "9ebf57ddeef7e4f5fb4d5ed2250f261e81fcc476d51114281bee6b41961c097a"
)


ATTENTION_REASON_ORDER = (
    "provider_specific_unresolved",
    "citation_identity_conflict",
    "database_identity_conflict",
    "cross_stage_conflict_citation_side",
    "cross_stage_conflict_database_side",
    "missing_title",
    "missing_name",
)

IDENTITY_ATTENTION_REASONS = {
    "provider_specific_unresolved",
    "citation_identity_conflict",
    "database_identity_conflict",
    "cross_stage_conflict_citation_side",
    "cross_stage_conflict_database_side",
}


def sha256_file(
    path: Path,
) -> str:
    h = hashlib.sha256()

    with path.open("rb") as fh:
        for block in iter(
            lambda: fh.read(1024 * 1024),
            b"",
        ):
            h.update(block)

    return h.hexdigest()


def verify_frozen_identity_dependency() -> None:
    actual = sha256_file(
        IDENTITY_IMPLEMENTATION
    )

    if (
        actual
        != FROZEN_IDENTITY_IMPLEMENTATION_SHA256
    ):
        raise RuntimeError(
            "Frozen identity implementation drift: "
            f"{actual} != "
            f"{FROZEN_IDENTITY_IMPLEMENTATION_SHA256}"
        )


verify_frozen_identity_dependency()


def sorted_unique(
    values: Iterable[str],
) -> list[str]:
    return sorted({
        str(value).strip()
        for value in values
        if str(value).strip()
    })


def result_bytes(
    result: dict,
) -> bytes:
    return (
        json.dumps(
            result,
            ensure_ascii=False,
            sort_keys=True,
            separators=(",", ":"),
        )
        + "\n"
    ).encode("utf-8")


def ordered_attention_reasons(
    reasons: Iterable[str],
) -> list[str]:
    values = set(reasons)

    unknown = (
        values
        - set(ATTENTION_REASON_ORDER)
    )

    if unknown:
        raise RuntimeError(
            "Unknown attention reasons: "
            + ", ".join(
                sorted(unknown)
            )
        )

    return [
        reason
        for reason
        in ATTENTION_REASON_ORDER
        if reason in values
    ]


def cross_stage_conflict_key(
    *,
    reason: str,
    citation_entity: str,
) -> str:
    return (
        "cross_stage_conflict:"
        + reason
        + ":"
        + citation_entity
    )


def build_cross_stage_screening_universe(
    database_identity: dict,
    citation_identity: dict,
) -> dict:
    """
    Build the complete provisional offline screening universe.

    All source identity entities must already have been generated by the
    frozen identity implementation.
    """

    database_entities = (
        database_identity.get(
            "entities"
        )
    )

    citation_entities = (
        citation_identity.get(
            "entities"
        )
    )

    if not isinstance(
        database_entities,
        list,
    ):
        raise RuntimeError(
            "database_identity lacks entity list"
        )

    if not isinstance(
        citation_entities,
        list,
    ):
        raise RuntimeError(
            "citation_identity lacks entity list"
        )

    # -------------------------------------------------------------
    # Validate unique source entity identifiers.
    # -------------------------------------------------------------

    database_keys = [
        entity[
            "provisional_entity_key"
        ]
        for entity in database_entities
    ]

    citation_keys = [
        entity[
            "provisional_entity_key"
        ]
        for entity in citation_entities
    ]

    if (
        len(database_keys)
        != len(set(database_keys))
    ):
        raise RuntimeError(
            "Duplicate database entity key"
        )

    if (
        len(citation_keys)
        != len(set(citation_keys))
    ):
        raise RuntimeError(
            "Duplicate citation entity key"
        )

    database_publications = [
        entity
        for entity in database_entities
        if entity[
            "screening_entity_class"
        ]
        == "publication"
    ]

    database_registries = [
        entity
        for entity in database_entities
        if entity[
            "screening_entity_class"
        ]
        == "software_registry"
    ]

    unknown_classes = {
        entity[
            "screening_entity_class"
        ]
        for entity in database_entities
        if entity[
            "screening_entity_class"
        ]
        not in {
            "publication",
            "software_registry",
        }
    }

    if unknown_classes:
        raise RuntimeError(
            "Unknown database screening entity classes: "
            + repr(
                sorted(
                    unknown_classes
                )
            )
        )

    for entity in citation_entities:
        if (
            entity[
                "screening_entity_class"
            ]
            != "publication"
        ):
            raise RuntimeError(
                "Citation identity layer contains "
                "non-publication entity"
            )

        if (
            len(
                entity[
                    "doi_values"
                ]
            )
            > 1
        ):
            raise RuntimeError(
                "Citation provisional entity "
                "contains multiple DOI values: "
                + entity[
                    "provisional_entity_key"
                ]
            )

    db_by_key = {
        entity[
            "provisional_entity_key"
        ]:
            entity
        for entity in database_publications
    }

    citation_by_key = {
        entity[
            "provisional_entity_key"
        ]:
            entity
        for entity in citation_entities
    }

    # -------------------------------------------------------------
    # Database identifier indexes.
    # -------------------------------------------------------------

    db_by_doi: dict[
        str,
        set[str],
    ] = defaultdict(set)

    db_by_pmid: dict[
        str,
        set[str],
    ] = defaultdict(set)

    for entity in database_publications:
        key = entity[
            "provisional_entity_key"
        ]

        for doi in entity[
            "doi_values"
        ]:
            db_by_doi[
                doi
            ].add(key)

        for pmid in entity[
            "pmid_values"
        ]:
            db_by_pmid[
                pmid
            ].add(key)

    duplicate_doi_indexes = {
        doi: sorted(keys)
        for doi, keys
        in db_by_doi.items()
        if len(keys) > 1
    }

    if duplicate_doi_indexes:
        raise RuntimeError(
            "DOI appears in multiple database "
            "publication entities: "
            + json.dumps(
                duplicate_doi_indexes,
                sort_keys=True,
            )
        )

    # -------------------------------------------------------------
    # Cross-stage publication linkage.
    # -------------------------------------------------------------

    automatic_links = []
    cross_stage_conflicts = []
    no_link_citation_keys = []

    for entity in sorted(
        citation_entities,
        key=lambda row:
            row[
                "provisional_entity_key"
            ],
    ):
        citation_key = entity[
            "provisional_entity_key"
        ]

        dois = entity[
            "doi_values"
        ]

        pmids = entity[
            "pmid_values"
        ]

        doi_database_keys = {
            db_key
            for doi in dois
            for db_key
            in db_by_doi.get(
                doi,
                set(),
            )
        }

        pmid_database_keys = {
            db_key
            for pmid in pmids
            for db_key
            in db_by_pmid.get(
                pmid,
                set(),
            )
        }

        # ---------------------------------------------------------
        # Exact DOI is primary, but conflicting PMID evidence
        # prevents automatic cross-stage linkage.
        # ---------------------------------------------------------

        if doi_database_keys:
            if (
                len(
                    doi_database_keys
                )
                != 1
            ):
                raise RuntimeError(
                    "Citation DOI maps to "
                    "multiple database entities: "
                    f"{citation_key} -> "
                    f"{sorted(doi_database_keys)}"
                )

            doi_database_key = next(
                iter(
                    doi_database_keys
                )
            )

            incompatible_pmid_keys = (
                pmid_database_keys
                - {
                    doi_database_key,
                }
            )

            if incompatible_pmid_keys:
                reason = (
                    "doi_and_pmid_"
                    "cross_stage_disagreement"
                )

                cross_stage_conflicts.append({
                    "conflict_key":
                        cross_stage_conflict_key(
                            reason=reason,
                            citation_entity=
                                citation_key,
                        ),

                    "reason":
                        reason,

                    "citation_entity":
                        citation_key,

                    "citation_doi_values":
                        sorted(dois),

                    "citation_pmid_values":
                        sorted(pmids),

                    "database_doi_entity_keys":
                        sorted(
                            doi_database_keys
                        ),

                    "database_pmid_entity_keys":
                        sorted(
                            pmid_database_keys
                        ),
                })

            else:
                automatic_links.append({
                    "citation_entity":
                        citation_key,

                    "database_entity":
                        doi_database_key,

                    "link_basis":
                        "exact_doi",
                })

        # ---------------------------------------------------------
        # A citation DOI absent from the database may not be
        # replaced by a database DOI merely because a PMID links.
        # ---------------------------------------------------------

        elif (
            dois
            and pmid_database_keys
        ):
            reason = (
                "citation_doi_absent_"
                "from_database_but_pmid_"
                "links_database_entity"
            )

            cross_stage_conflicts.append({
                "conflict_key":
                    cross_stage_conflict_key(
                        reason=reason,
                        citation_entity=
                            citation_key,
                    ),

                "reason":
                    reason,

                "citation_entity":
                    citation_key,

                "citation_doi_values":
                    sorted(dois),

                "citation_pmid_values":
                    sorted(pmids),

                "database_doi_entity_keys":
                    [],

                "database_pmid_entity_keys":
                    sorted(
                        pmid_database_keys
                    ),
            })

        # ---------------------------------------------------------
        # DOI-less citation entity: exact PMID may link only when
        # all database evidence resolves to one publication entity.
        # ---------------------------------------------------------

        elif (
            not dois
            and pmid_database_keys
        ):
            if (
                len(
                    pmid_database_keys
                )
                == 1
            ):
                automatic_links.append({
                    "citation_entity":
                        citation_key,

                    "database_entity":
                        next(
                            iter(
                                pmid_database_keys
                            )
                        ),

                    "link_basis":
                        "exact_unique_pmid",
                })

            else:
                reason = (
                    "pmid_maps_multiple_"
                    "database_entities"
                )

                cross_stage_conflicts.append({
                    "conflict_key":
                        cross_stage_conflict_key(
                            reason=reason,
                            citation_entity=
                                citation_key,
                        ),

                    "reason":
                        reason,

                    "citation_entity":
                        citation_key,

                    "citation_doi_values":
                        [],

                    "citation_pmid_values":
                        sorted(pmids),

                    "database_doi_entity_keys":
                        [],

                    "database_pmid_entity_keys":
                        sorted(
                            pmid_database_keys
                        ),
                })

        else:
            no_link_citation_keys.append(
                citation_key
            )

    automatic_links.sort(
        key=lambda row: (
            row["database_entity"],
            row["citation_entity"],
            row["link_basis"],
        )
    )

    cross_stage_conflicts.sort(
        key=lambda row: (
            row["reason"],
            row["citation_entity"],
        )
    )

    no_link_citation_keys.sort()

    link_by_citation = {}

    for row in automatic_links:
        citation_key = row[
            "citation_entity"
        ]

        if citation_key in link_by_citation:
            raise RuntimeError(
                "Citation entity assigned "
                "multiple automatic links: "
                + citation_key
            )

        link_by_citation[
            citation_key
        ] = row

    conflict_by_citation = {}

    for row in cross_stage_conflicts:
        citation_key = row[
            "citation_entity"
        ]

        if citation_key in conflict_by_citation:
            raise RuntimeError(
                "Citation entity assigned "
                "multiple cross-stage conflicts: "
                + citation_key
            )

        conflict_by_citation[
            citation_key
        ] = row

    disposition_keys = (
        set(
            link_by_citation
        )
        | set(
            conflict_by_citation
        )
        | set(
            no_link_citation_keys
        )
    )

    if (
        disposition_keys
        != set(
            citation_by_key
        )
    ):
        raise RuntimeError(
            "Cross-stage disposition does not "
            "cover citation identity universe"
        )

    if (
        set(link_by_citation)
        & set(conflict_by_citation)
    ):
        raise RuntimeError(
            "Citation entity both linked "
            "and conflict-held cross-stage"
        )

    # -------------------------------------------------------------
    # Publication components.
    # -------------------------------------------------------------

    publication_components: dict[
        str,
        dict,
    ] = {}

    db_component_by_entity = {}

    for entity in sorted(
        database_publications,
        key=lambda row:
            row[
                "provisional_entity_key"
            ],
    ):
        database_key = entity[
            "provisional_entity_key"
        ]

        component_id = (
            "publication_component:"
            "database:"
            + database_key
        )

        db_component_by_entity[
            database_key
        ] = component_id

        publication_components[
            component_id
        ] = {
            "screening_component_id":
                component_id,

            "screening_entity_class":
                "publication",

            "database_entity_keys": [
                database_key
            ],

            "citation_entity_keys":
                [],

            "cross_stage_link_bases":
                [],

            "doi_values":
                set(
                    entity[
                        "doi_values"
                    ]
                ),

            "pmid_values":
                set(
                    entity[
                        "pmid_values"
                    ]
                ),

            "openalex_id_values":
                set(),

            "omid_values":
                set(),

            "titles":
                set(
                    entity[
                        "titles"
                    ]
                ),

            "years":
                set(
                    entity[
                        "years"
                    ]
                ),

            "database_identity_statuses": {
                entity[
                    "identity_status"
                ]
            },

            "citation_identity_statuses":
                set(),

            "database_source_record_ids":
                set(
                    entity[
                        "source_record_ids"
                    ]
                ),

            "citation_source_record_ids":
                set(),

            "attention_reasons":
                set(),

            "cross_stage_conflict_keys":
                set(),
        }

        if (
            entity[
                "identity_status"
            ]
            == "conflict_hold"
        ):
            publication_components[
                component_id
            ][
                "attention_reasons"
            ].add(
                "database_identity_conflict"
            )

    # -------------------------------------------------------------
    # Attach safely linked citation identities or create citation-
    # only publication components.
    # -------------------------------------------------------------

    citation_component_by_entity = {}

    for entity in sorted(
        citation_entities,
        key=lambda row:
            row[
                "provisional_entity_key"
            ],
    ):
        citation_key = entity[
            "provisional_entity_key"
        ]

        link = link_by_citation.get(
            citation_key
        )

        if link is not None:
            component_id = (
                db_component_by_entity[
                    link[
                        "database_entity"
                    ]
                ]
            )

            component = (
                publication_components[
                    component_id
                ]
            )

            component[
                "citation_entity_keys"
            ].append(
                citation_key
            )

            component[
                "cross_stage_link_bases"
            ].append(
                link[
                    "link_basis"
                ]
            )

        else:
            component_id = (
                "publication_component:"
                "citation:"
                + citation_key
            )

            if (
                component_id
                in publication_components
            ):
                raise RuntimeError(
                    "Duplicate publication component: "
                    + component_id
                )

            component = {
                "screening_component_id":
                    component_id,

                "screening_entity_class":
                    "publication",

                "database_entity_keys":
                    [],

                "citation_entity_keys": [
                    citation_key
                ],

                "cross_stage_link_bases":
                    [],

                "doi_values":
                    set(),

                "pmid_values":
                    set(),

                "openalex_id_values":
                    set(),

                "omid_values":
                    set(),

                "titles":
                    set(),

                "years":
                    set(),

                "database_identity_statuses":
                    set(),

                "citation_identity_statuses":
                    set(),

                "database_source_record_ids":
                    set(),

                "citation_source_record_ids":
                    set(),

                "attention_reasons":
                    set(),

                "cross_stage_conflict_keys":
                    set(),
            }

            publication_components[
                component_id
            ] = component

        citation_component_by_entity[
            citation_key
        ] = component_id

        component[
            "doi_values"
        ].update(
            entity[
                "doi_values"
            ]
        )

        component[
            "pmid_values"
        ].update(
            entity[
                "pmid_values"
            ]
        )

        component[
            "openalex_id_values"
        ].update(
            entity[
                "openalex_id_values"
            ]
        )

        component[
            "omid_values"
        ].update(
            entity[
                "omid_values"
            ]
        )

        component[
            "titles"
        ].update(
            entity[
                "titles"
            ]
        )

        component[
            "years"
        ].update(
            entity[
                "years"
            ]
        )

        component[
            "citation_identity_statuses"
        ].add(
            entity[
                "identity_status"
            ]
        )

        component[
            "citation_source_record_ids"
        ].update(
            entity[
                "source_record_ids"
            ]
        )

        if (
            entity[
                "identity_status"
            ]
            == "provider_specific_unresolved"
        ):
            component[
                "attention_reasons"
            ].add(
                "provider_specific_unresolved"
            )

        if (
            entity[
                "identity_status"
            ]
            == "conflict_hold"
        ):
            component[
                "attention_reasons"
            ].add(
                "citation_identity_conflict"
            )

    # -------------------------------------------------------------
    # Cross-stage conflict evidence remains unmerged.
    # Mark both sides of every conflict.
    # -------------------------------------------------------------

    for conflict in cross_stage_conflicts:
        citation_key = conflict[
            "citation_entity"
        ]

        citation_component_id = (
            citation_component_by_entity[
                citation_key
            ]
        )

        citation_component = (
            publication_components[
                citation_component_id
            ]
        )

        citation_component[
            "attention_reasons"
        ].add(
            "cross_stage_conflict_citation_side"
        )

        citation_component[
            "cross_stage_conflict_keys"
        ].add(
            conflict[
                "conflict_key"
            ]
        )

        implicated_database_keys = set(
            conflict[
                "database_doi_entity_keys"
            ]
        ) | set(
            conflict[
                "database_pmid_entity_keys"
            ]
        )

        for database_key in sorted(
            implicated_database_keys
        ):
            component_id = (
                db_component_by_entity[
                    database_key
                ]
            )

            component = (
                publication_components[
                    component_id
                ]
            )

            component[
                "attention_reasons"
            ].add(
                "cross_stage_conflict_database_side"
            )

            component[
                "cross_stage_conflict_keys"
            ].add(
                conflict[
                    "conflict_key"
                ]
            )

    # -------------------------------------------------------------
    # Finalize publication components.
    # -------------------------------------------------------------

    final_publication_components = []

    for component_id in sorted(
        publication_components
    ):
        component = (
            publication_components[
                component_id
            ]
        )

        if (
            len(
                component[
                    "database_entity_keys"
                ]
            )
            > 1
        ):
            raise RuntimeError(
                "Publication component contains "
                "multiple database identities: "
                + component_id
            )

        # A safely linked component may contain multiple citation
        # provisional identities, but different DOI values are
        # retained rather than interpreted as equivalent.
        #
        # Under the automatic-link rules, linked components should
        # not introduce a second distinct DOI.
        if (
            component[
                "database_entity_keys"
            ]
            and len(
                component[
                    "doi_values"
                ]
            )
            > 1
        ):
            raise RuntimeError(
                "Automatic cross-stage component "
                "contains multiple DOI values: "
                + component_id
            )

        if not component["titles"]:
            component[
                "attention_reasons"
            ].add(
                "missing_title"
            )

        attention = (
            ordered_attention_reasons(
                component[
                    "attention_reasons"
                ]
            )
        )

        final_publication_components.append({
            "screening_component_id":
                component_id,

            "screening_entity_class":
                "publication",

            "database_entity_keys":
                sorted(
                    component[
                        "database_entity_keys"
                    ]
                ),

            "citation_entity_keys":
                sorted(
                    component[
                        "citation_entity_keys"
                    ]
                ),

            "cross_stage_link_bases":
                sorted(
                    component[
                        "cross_stage_link_bases"
                    ]
                ),

            "doi_values":
                sorted(
                    component[
                        "doi_values"
                    ]
                ),

            "pmid_values":
                sorted(
                    component[
                        "pmid_values"
                    ]
                ),

            "openalex_id_values":
                sorted(
                    component[
                        "openalex_id_values"
                    ]
                ),

            "omid_values":
                sorted(
                    component[
                        "omid_values"
                    ]
                ),

            "titles":
                sorted(
                    component[
                        "titles"
                    ]
                ),

            "years":
                sorted(
                    component[
                        "years"
                    ]
                ),

            "database_identity_statuses":
                sorted(
                    component[
                        "database_identity_statuses"
                    ]
                ),

            "citation_identity_statuses":
                sorted(
                    component[
                        "citation_identity_statuses"
                    ]
                ),

            "database_source_record_ids":
                sorted(
                    component[
                        "database_source_record_ids"
                    ]
                ),

            "citation_source_record_ids":
                sorted(
                    component[
                        "citation_source_record_ids"
                    ]
                ),

            "cross_stage_conflict_keys":
                sorted(
                    component[
                        "cross_stage_conflict_keys"
                    ]
                ),

            "attention_reasons":
                attention,

            "identity_attention":
                any(
                    reason
                    in IDENTITY_ATTENTION_REASONS
                    for reason in attention
                ),

            "metadata_attention":
                "missing_title"
                in attention,
        })

    # -------------------------------------------------------------
    # Software-registry components remain independent.
    # -------------------------------------------------------------

    final_registry_components = []

    for entity in sorted(
        database_registries,
        key=lambda row:
            row[
                "provisional_entity_key"
            ],
    ):
        registry_key = entity[
            "provisional_entity_key"
        ]

        component_id = (
            "software_registry_component:"
            + registry_key
        )

        reasons = set()

        if not entity["titles"]:
            reasons.add(
                "missing_name"
            )

        final_registry_components.append({
            "screening_component_id":
                component_id,

            "screening_entity_class":
                "software_registry",

            "database_entity_keys": [
                registry_key
            ],

            "citation_entity_keys":
                [],

            "titles":
                sorted(
                    entity[
                        "titles"
                    ]
                ),

            "doi_values":
                sorted(
                    entity[
                        "doi_values"
                    ]
                ),

            "pmid_values":
                sorted(
                    entity[
                        "pmid_values"
                    ]
                ),

            "source_record_ids":
                sorted(
                    entity[
                        "source_record_ids"
                    ]
                ),

            "attention_reasons":
                ordered_attention_reasons(
                    reasons
                ),

            "identity_attention":
                False,

            "metadata_attention":
                bool(reasons),
        })

    # -------------------------------------------------------------
    # Provenance / membership invariants.
    # -------------------------------------------------------------

    represented_database_keys = [
        key
        for component
        in final_publication_components
        for key
        in component[
            "database_entity_keys"
        ]
    ] + [
        key
        for component
        in final_registry_components
        for key
        in component[
            "database_entity_keys"
        ]
    ]

    represented_citation_keys = [
        key
        for component
        in final_publication_components
        for key
        in component[
            "citation_entity_keys"
        ]
    ]

    if Counter(
        represented_database_keys
    ) != Counter(
        database_keys
    ):
        raise RuntimeError(
            "Database screening-entity "
            "membership was lost or duplicated"
        )

    if Counter(
        represented_citation_keys
    ) != Counter(
        citation_keys
    ):
        raise RuntimeError(
            "Citation screening-entity "
            "membership was lost or duplicated"
        )

    # -------------------------------------------------------------
    # Derived diagnostics.
    # -------------------------------------------------------------

    links_by_database = defaultdict(
        list
    )

    for row in automatic_links:
        links_by_database[
            row[
                "database_entity"
            ]
        ].append(
            row[
                "citation_entity"
            ]
        )

    multi_link_database_entities = {
        key: sorted(values)
        for key, values
        in links_by_database.items()
        if len(values) > 1
    }

    link_basis_counts = Counter(
        row[
            "link_basis"
        ]
        for row in automatic_links
    )

    cross_stage_conflict_types = Counter(
        row[
            "reason"
        ]
        for row in cross_stage_conflicts
    )

    titleless_database_initial = {
        entity[
            "provisional_entity_key"
        ]
        for entity
        in database_publications
        if not entity[
            "titles"
        ]
    }

    titleless_citation_initial = {
        entity[
            "provisional_entity_key"
        ]
        for entity
        in citation_entities
        if not entity[
            "titles"
        ]
    }

    linked_database_keys = set(
        links_by_database
    )

    titleless_database_linked = (
        titleless_database_initial
        & linked_database_keys
    )

    titleless_database_rescued = {
        database_key
        for database_key
        in titleless_database_linked
        if publication_components[
            db_component_by_entity[
                database_key
            ]
        ][
            "titles"
        ]
    }

    titleless_citation_linked = {
        citation_key
        for citation_key
        in titleless_citation_initial
        if citation_key
        in link_by_citation
    }

    titleless_citation_rescued = {
        citation_key
        for citation_key
        in titleless_citation_linked
        if publication_components[
            db_component_by_entity[
                link_by_citation[
                    citation_key
                ][
                    "database_entity"
                ]
            ]
        ][
            "titles"
        ]
    }

    publication_identity_attention = [
        component
        for component
        in final_publication_components
        if component[
            "identity_attention"
        ]
    ]

    publication_metadata_attention = [
        component
        for component
        in final_publication_components
        if component[
            "metadata_attention"
        ]
    ]

    publication_any_attention = [
        component
        for component
        in final_publication_components
        if (
            component[
                "identity_attention"
            ]
            or component[
                "metadata_attention"
            ]
        )
    ]

    registry_attention = [
        component
        for component
        in final_registry_components
        if component[
            "attention_reasons"
        ]
    ]

    attention_reason_combinations = Counter(
        "|".join(
            component[
                "attention_reasons"
            ]
        )
        for component
        in (
            final_publication_components
            + final_registry_components
        )
        if component[
            "attention_reasons"
        ]
    )

    return {
        "database_input_entity_count":
            len(
                database_entities
            ),

        "citation_input_entity_count":
            len(
                citation_entities
            ),

        "automatic_link_count":
            len(
                automatic_links
            ),

        "automatic_link_basis_counts":
            dict(
                sorted(
                    link_basis_counts.items()
                )
            ),

        "unique_database_publications_linked":
            len(
                links_by_database
            ),

        "database_publications_with_multiple_citation_links":
            len(
                multi_link_database_entities
            ),

        "multi_link_database_entities":
            dict(
                sorted(
                    multi_link_database_entities.items()
                )
            ),

        "cross_stage_conflict_count":
            len(
                cross_stage_conflicts
            ),

        "cross_stage_conflict_types":
            dict(
                sorted(
                    cross_stage_conflict_types.items()
                )
            ),

        "citation_entities_without_cross_stage_link":
            len(
                no_link_citation_keys
            ),

        "publication_component_count":
            len(
                final_publication_components
            ),

        "software_registry_component_count":
            len(
                final_registry_components
            ),

        "screening_component_count":
            (
                len(
                    final_publication_components
                )
                + len(
                    final_registry_components
                )
            ),

        "initial_titleless_database_publications":
            len(
                titleless_database_initial
            ),

        "titleless_database_publications_receiving_link":
            len(
                titleless_database_linked
            ),

        "titleless_database_publications_rescued":
            len(
                titleless_database_rescued
            ),

        "initial_titleless_citation_entities":
            len(
                titleless_citation_initial
            ),

        "titleless_citation_entities_receiving_link":
            len(
                titleless_citation_linked
            ),

        "titleless_citation_entities_rescued":
            len(
                titleless_citation_rescued
            ),

        "publication_components_missing_title":
            len(
                publication_metadata_attention
            ),

        "publication_components_requiring_identity_attention":
            len(
                publication_identity_attention
            ),

        "publication_components_requiring_any_attention":
            len(
                publication_any_attention
            ),

        "software_registry_components_requiring_attention":
            len(
                registry_attention
            ),

        "screening_components_requiring_any_attention":
            (
                len(
                    publication_any_attention
                )
                + len(
                    registry_attention
                )
            ),

        "attention_reason_combinations":
            dict(
                sorted(
                    attention_reason_combinations.items()
                )
            ),

        "automatic_links":
            automatic_links,

        "cross_stage_conflicts":
            cross_stage_conflicts,

        "publication_components":
            final_publication_components,

        "software_registry_components":
            final_registry_components,
    }


def main() -> int:
    parser = argparse.ArgumentParser()

    parser.add_argument(
        "--database",
        required=True,
        type=Path,
    )

    parser.add_argument(
        "--citation",
        required=True,
        type=Path,
    )

    args = parser.parse_args()

    database_rows = (
        identity.read_tsv(
            args.database
        )
    )

    citation_rows = (
        identity.read_tsv(
            args.citation
        )
    )

    database_identity = (
        identity.build_database_screening_entities(
            database_rows
        )
    )

    citation_identity = (
        identity.build_citation_publication_entities(
            citation_rows
        )
    )

    result = (
        build_cross_stage_screening_universe(
            database_identity,
            citation_identity,
        )
    )

    summary_keys = (
        "database_input_entity_count",
        "citation_input_entity_count",
        "automatic_link_count",
        "automatic_link_basis_counts",
        "unique_database_publications_linked",
        "database_publications_with_multiple_citation_links",
        "cross_stage_conflict_count",
        "cross_stage_conflict_types",
        "citation_entities_without_cross_stage_link",
        "publication_component_count",
        "software_registry_component_count",
        "screening_component_count",
        "initial_titleless_database_publications",
        "titleless_database_publications_receiving_link",
        "titleless_database_publications_rescued",
        "initial_titleless_citation_entities",
        "titleless_citation_entities_receiving_link",
        "titleless_citation_entities_rescued",
        "publication_components_missing_title",
        "publication_components_requiring_identity_attention",
        "publication_components_requiring_any_attention",
        "software_registry_components_requiring_attention",
        "screening_components_requiring_any_attention",
        "attention_reason_combinations",
    )

    summary = {
        key: result[key]
        for key in summary_keys
    }

    print(
        json.dumps(
            summary,
            indent=2,
            ensure_ascii=False,
            sort_keys=True,
        )
    )

    return 0


if __name__ == "__main__":
    raise SystemExit(
        main()
    )
